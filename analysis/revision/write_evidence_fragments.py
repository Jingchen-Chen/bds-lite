"Generate new manuscript evidence fragments and claims only from verified CSVs."

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    tables = ROOT / "revision/tables"
    draft = ROOT / "revision/manuscript"
    draft.mkdir(exist_ok=True)
    stats = list(csv.DictReader((tables / "volume_primary_statistics.csv").open()))
    lines = [
        r"\begin{tabular}{lllrrrr}",
        r"Dataset & Metric & Units & Effect & CI lower & CI upper & Holm p \\",
        r"\hline",
    ]
    completions = [
        json.loads(p.read_text())
        for p in (ROOT / "revision/volume_results").rglob("volume_complete.json")
    ]
    report = [
        "# Stacked-volume findings — index-grid evaluation",
        "",
        (
            f"Completed cohorts: {len(completions)}; volumes: "
            f"{sum(r['volumes'] for r in completions)}; volume-class rows: "
            f"{sum(r['class_rows'] for r in completions)}. "
            + (
                "Class/frame and seed averaging uses patient/case units. "
                "Named anatomy needs review."
            )
        ),
        "",
        ("| Dataset | Endpoint | Paired n | Full−U mean | 95% bootstrap interval | Holm p |"),
        "|---|---|---:|---:|---|---:|",
    ]
    for row in stats:
        if row["family"] != "V":
            continue
        metric = row["metric"].replace("_", r"\_")
        pvalue = f"{float(row['p_holm']):.6f}" if row["p_holm"] else "--"
        effect = f"{float(row['mean_difference']):.6f}"
        low = f"{float(row['ci95_low']):.6f}"
        high = f"{float(row['ci95_high']):.6f}"
        dataset, count = row["dataset"], row["n"]
        lines.append(
            f"{dataset} & {metric} & {count} & {effect} & {low} & {high} & {pvalue} " + r"\\"
        )
        report.append(
            f"| {dataset} | {row['metric']} | {count} | {effect} | [{low}, {high}] | {pvalue} |"
        )
    lines.append(r"\end{tabular}")
    (tables / "volume_primary_statistics.tex").write_text("\n".join(lines) + "\n")
    report += [
        "",
        (
            "Both datasets have higher mean volume Dice for the full "
            "recipe. ACDC surface distances are worse on average; Synapse"
            " distance differences remain uncertain. Holm-adjusted "
            "volume-Dice evidence is stronger on Synapse than ACDC. "
            "Neither Dice interval lies entirely beyond the chosen "
            "engineering SESOI. These findings do not replace or erase "
            "different slice-level outcomes."
        ),
        "",
        (
            "Synapse surface complete-case inference excludes one case; "
            "all-case diagonal-penalty sensitivity is retained in "
            "volume_primary_statistics.csv. Those penalties are not "
            "measured distances. No millimetre-based practical-"
            "equivalence statement is made."
        ),
        "",
        (
            "Synapse uses original H5 labels and nearest-output zoom; "
            "processed inputs were bilinear resized rather than the "
            "official reference cubic input zoom. ACDC uses the observed "
            "processed-grid stacks, without verified native spacing or "
            "ED/ES assignment. No EF/mass results are reported. All "
            "Synapse per-class rows retain numeric IDs until anatomical "
            "names are verified."
        ),
        "",
        (
            "All per-volume values and source/output hashes are under "
            "volume_results/. KDTree distances matched explicit EDT "
            "distances in synthetic3D checks. The full raw reference-"
            "empty convention and robust alternative are both saved. "
            "Four real-volume EDT spot-checks passed; complete "
            "manuscript integration remains pending."
        ),
    ]
    (ROOT / "revision/VOLUME_FINDINGS.md").write_text("\n".join(report) + "\n")
    fragment = r"""% Generated by analysis/revision/write_evidence_fragments.py.
% Numeric sources: ../tables/official_isic_primary_statistics.csv and
% ../tables/volume_primary_statistics.csv. Not a completed revised manuscript.
\section{Independent-image and stacked-volume evaluation (revision draft)}
The official ISIC evaluation does not establish the proposed surface-distance
benefit of the full recipe. The observed overlap, boundary and surface effects
must be reported together. Engineering SESOI classifications are conditional on
the trained seeds and do not demonstrate clinical equivalence.
\begin{table}[ht]
\centering\small
\input{../tables/official_isic_primary_statistics.tex}
\caption{Registered official-image primary comparison and separate surface
sensitivity. Effects are full recipe minus U-Net. Positive surface differences
favor U-Net. Missing surface units and correction scope are retained in the CSV.}
\end{table}
For stacked volumes, mean Dice is higher for the full recipe on both datasets,
while surface behavior remains conditional. Patient/case averaging changes the
estimand relative to slice-level summaries; both must remain visible.
\begin{table}[ht]
\centering\small
\input{../tables/volume_primary_statistics.tex}
\caption{Exploratory volume family V. ACDC distances use the processed index
grid; Synapse distances use the original H5 index grid. Neither is verified in
millimetres. The source CSV reports complete-unit eligibility and sensitivities.}
\end{table}
\paragraph{Matched gate intervention.}
The gate was replaced by unit modulation on the same trained checkpoints.
Changed masks and measurable rank differences preclude a claim of exact invariance.
All primary mean-effect intervals fall within the specified engineering SESOI
bands for the tested seeds. This exploratory analysis is distinct from retraining
without the gate and does not demonstrate clinical equivalence or zero latency.
\input{../tables/gate_identity_effects.tex}
Physical-unit distances, ejection fraction and myocardial mass remain unavailable
without trustworthy geometry. Anatomical-name interpretation of Synapse labels
is withheld pending preprocessing-map verification. Legacy GSL and single-seed
Attention references are separate families, not missing matched comparators.
"""
    (draft / "verified_results_draft.tex").write_text(fragment)
    (
        draft / "acknowledgments_draft.tex"
    ).write_text(r"""% HUMAN: verify complete tool inventory and purposes before submission.
The authors previously disclosed using ChatGPT for sentence structure and
readability during manuscript preparation. During revision, Codex assisted with
code implementation, repository and data audits, statistical scripting, and
language drafting. The authors remain responsible for verifying the code,
numerical evidence, citations, and final manuscript.
% HUMAN: verify additional tools, including Claude if used, and purposes.
""")
    claims = [
        dict(
            id="ISIC-independent",
            claim="Full recipe has no established official-test HD95 advantage",
            source="revision/tables/official_isic_primary_statistics.csv",
            row="metric=hd95; family=P",
            scope=("conditional trained seeds; official image units; patient independence unknown"),
        ),
        dict(
            id="Volume-Dice",
            claim="Positive mean volume Dice differences on both studied datasets",
            source="revision/tables/volume_primary_statistics.csv",
            row="metric=dsc; family=V",
            scope="ACDC patients/Synapse cases; index grids; not general superiority",
        ),
        dict(
            id="Volume-surfaces",
            claim="ACDC surface means worse and Synapse surface differences uncertain",
            source="revision/tables/volume_primary_statistics.csv",
            row="metric=hd95/assd_pooled; family=V",
            scope="uncalibrated index units; no physical or clinical equivalence",
        ),
    ]
    with (draft / "claim_evidence_table.csv").open("w") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(claims[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(claims)
    (draft / "README.md").write_text(
        "Generated evidence fragments for author integration, not a "
        "complete PeerJ manuscript. Run make_tables.py then "
        "write_evidence_fragments.py. Original submitted source "
        "remains preserved under recovered/peerj-submission. Current "
        "environment has no pdflatex/latexmk, so these new fragments "
        "have not been compiled. AI tool inventory and full narrative"
        " require author review.\n"
    )
    print("Generated traceable volume table, findings and manuscript fragments")


if __name__ == "__main__":
    main()
