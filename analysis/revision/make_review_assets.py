from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results/posthoc_review_20261112"
GEN = ROOT / "paper/generated"
KEYS: dict[str, str] = {}
MINUS = "$-$"
ARM = {
    "U": "U",
    "D": "D",
    "D+F+G": "D+F+G",
    "BDS-Lite": "BDS-Lite",
    "unet": "U",
    "full": "BDS-Lite",
    "gsl": "U-Net+GSL",
    "decoder": "D",
    "kd_band": "D+KD-band",
    "kd_full": "D+KD-full",
    "kd_band_peer": r"D+KD-band$_{\mathrm{cmp}}$",
    "decoder_aug": r"D$_{\mathrm{aug}}$",
    "kd_band_aug": r"D+KD-band$_{\mathrm{aug}}$",
}
DATASET = {"isic2018": "ISIC2018", "acdc": "ACDC", "synapse": "Synapse"}
METRIC = {
    "boundary_f1": "Boundary F1",
    "dsc": "DSC",
    "iou": "IoU",
    "hd95": "HD95 (px)",
    "assd": "ASSD (px)",
}
EFFECT = {
    "decoder without surface": ("dec", "D $-$ U"),
    "distillation+gate without surface": ("nosurf", "D+F+G $-$ D"),
    "distillation+gate with surface": ("surf", "BDS-Lite $-$ D+S"),
}
RULE = {
    "inverse variance, normal (registered)": ("reg", "Inverse variance, normal (prespecified)"),
    "inverse variance, t (Satterthwaite)": ("ivt", "Inverse variance, $t$ interval"),
    "equal weights, normal": ("eq", "Equal weights, normal"),
    "equal weights, t (Satterthwaite)": ("eqt", "Equal weights, $t$ interval"),
    "inverse variance without isic2018, normal": ("noisic", "Inverse variance without ISIC2018"),
    "inverse variance without acdc, normal": ("noacdc", "Inverse variance without ACDC"),
    "inverse variance without synapse, normal": ("nosyn", "Inverse variance without Synapse"),
}
READING = {
    "gain, size unclear": "gain of unclear size",
    "harm, size unclear": "deficit of unclear size",
    "relevant harm": "relevant deficit",
}


def read(name: str) -> list[dict]:
    with (SRC / name).open() as stream:
        return list(csv.DictReader(stream))


def put(key: str, value: str) -> None:
    if key in KEYS and KEYS[key] != value:
        raise ValueError(f"conflicting key {key}")
    KEYS[key] = value


def num(value: float, digits: int, signed: bool = False) -> str:
    text = f"{abs(value):.{digits}f}"
    if float(text) == 0:
        return text
    if value < 0:
        return MINUS + text
    return ("+" if signed else "") + text


def span(low: float, high: float, digits: int) -> str:
    return f"{num(low, digits)} to {num(high, digits)}"


def pvalue(p: float) -> str:
    if p >= 0.001:
        return f"{p:.3f}" if p < 0.1 else f"{p:.2f}"
    mantissa, exponent = f"{p:.1e}".split("e")
    return rf"${mantissa}\times10^{{{int(exponent)}}}$"


def write(name: str, lines: list[str]) -> None:
    (GEN / name).write_text("\n".join(lines) + "\n")


def interaction() -> None:
    rows = read("interaction.csv")
    lines = [
        "% generated by analysis/revision/make_review_assets.py from posthoc_review_20261112/interaction.csv",
        r"\begin{tabular}{llrrrlrll}",
        r"\toprule",
        r"Runs & Metric & $\Delta$ no aug. & $\Delta$ aug. & $I$ & Prespecified-form 95\% CI & $p$ & Crossed-model 95\% CI & Bootstrap 95\% CI \\",
        r"\midrule",
    ]
    for r in rows:
        tag = "all" if r["runs"].startswith("all") else "matched"
        metric = r["metric"]
        digits = 2 if metric in ("hd95", "assd") else 4
        f = lambda k, r=r: float(r[k])  # noqa: E731
        key = f"RV.int.{tag}.{metric}"
        put(f"{key}.est", num(f("interaction"), digits, True))
        put(f"{key}.abs", num(abs(f("interaction")), digits))
        put(f"{key}.text", span(f("registered_form_low"), f("registered_form_high"), digits))
        put(f"{key}.p", pvalue(f("registered_form_p")))
        put(f"{key}.mixed.text", span(f("mixed_low"), f("mixed_high"), digits))
        put(f"{key}.boot.text", span(f("bootstrap_low"), f("bootstrap_high"), digits))
        label = "17/17 and 10/10" if tag == "all" else "10 per arm (seeds 201--210)"
        lines.append(
            f"{label} & {METRIC[metric]} & {num(f('simple_noaug'), digits, True)} & "
            f"{num(f('simple_aug'), digits, True)} & {num(f('interaction'), digits, True)} & "
            f"[{num(f('registered_form_low'), digits, True)}, {num(f('registered_form_high'), digits, True)}] & "
            f"{pvalue(f('registered_form_p'))} & "
            f"[{num(f('mixed_low'), digits, True)}, {num(f('mixed_high'), digits, True)}] & "
            f"[{num(f('bootstrap_low'), digits, True)}, {num(f('bootstrap_high'), digits, True)}] \\\\"
        )
        if metric == "assd" and tag == "all":
            lines.append(r"\addlinespace")
    first = rows[0]
    put("RV.int.df", f"{float(first['registered_form_df']):.1f}")
    b = next(r for r in rows if r["metric"] == "boundary_f1" and r["runs"].startswith("all"))
    put("RV.int.all.boundary_f1.df", f"{float(b['registered_form_df']):.1f}")
    put("RV.int.all.boundary_f1.se", f"{float(b['registered_form_se']):.4f}")
    put("RV.int.all.boundary_f1.se.naive", f"{float(b['independent_contrasts_se']):.4f}")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("tab_s_review_interaction.tex", lines)


def pooling() -> None:
    rows = [r for r in read("pooling_sensitivity.csv") if r["metric"] == "boundary_f1"]
    lines = [
        "% generated by analysis/revision/make_review_assets.py from posthoc_review_20261112/pooling_sensitivity.csv",
        r"\begin{tabular}{llrll}",
        r"\toprule",
        r"Contrast & Pooling rule & Estimate & 95\% CI & Reading \\",
        r"\midrule",
    ]
    previous = None
    for r in rows:
        if r["rule"] not in RULE:
            continue  # DerSimonian-Laird equals the fixed-effect summary here (tau2 = 0)
        tag, label = EFFECT[r["effect"]]
        rule, rule_label = RULE[r["rule"]]
        est, low, high = float(r["estimate"]), float(r["low"]), float(r["high"])
        put(f"RV.pool.{tag}.{rule}.est", num(est, 4, True))
        put(f"RV.pool.{tag}.{rule}.text", span(low, high, 4))
        if r["weight_share"]:
            put(f"RV.pool.{tag}.{rule}.share", f"{100 * float(r['weight_share']):.0f}")
        if previous not in (None, tag):
            lines.append(r"\addlinespace")
        reading = READING.get(r["classification"], r["classification"])
        lines.append(
            f"{label if previous != tag else ''} & {rule_label} & {num(est, 4, True)} & "
            f"[{num(low, 4, True)}, {num(high, 4, True)}] & {reading} \\\\"
        )
        previous = tag
    tau = {r["effect"]: r["rule"] for r in rows if r["rule"].startswith("DerSimonian")}
    if any("tau2=0)" not in v for v in tau.values()):
        raise ValueError("random-effects summary no longer equals the fixed-effect summary")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("tab_s_review_pooling.tex", lines)


def run_sd() -> None:
    rows = read("run_sd.csv")
    lines = [
        "% generated by analysis/revision/make_review_assets.py from posthoc_review_20261112/run_sd.csv",
        r"\begin{tabular}{lllrrr}",
        r"\toprule",
        r"Dataset & Test set & Arm & Runs & Mean & SD between runs \\",
        r"\midrule",
    ]
    for r in rows:
        put(f"RV.sd.{r['dataset']}.{r['arm']}", f"{float(r['sd']):.4f}")
        lines.append(
            f"{DATASET[r['dataset']]} & {r['test_set'].replace('101-150', '101--150')} & {ARM[r['arm']]} & {r['runs']} & "
            f"{float(r['mean']):.4f} & {float(r['sd']):.4f} \\\\"
        )
    for dataset in ("isic2018", "acdc"):
        values = [float(r["sd"]) for r in rows if r["dataset"] == dataset]
        put(f"RV.sd.{dataset}.min", f"{min(values):.4f}")
        put(f"RV.sd.{dataset}.max", f"{max(values):.4f}")
        put(f"RV.sd.{dataset}.arms", str(len(values)))
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("tab_s_review_run_sd.tex", lines)


def errors() -> None:
    rows = read("missed_false_alarm.csv")
    head = [
        r"\toprule",
        r"Dataset, test set & Arm & Runs & Missed structures (\%) & False alarms (\%) \\",
        r"\midrule",
    ]

    def body(keep: set[str]) -> list[str]:
        out, previous = [], None
        for r in rows:
            if r["arm"] not in keep:
                continue
            group = (r["dataset"], r["test_set"])
            if previous not in (None, group):
                out.append(r"\addlinespace")
            test_set = re.sub(r"(\d)-(\d)", r"\1--\2", r["test_set"])
            where = f"{DATASET[r['dataset']]}, {test_set}" if previous != group else ""
            alarm = (
                "--"
                if r["false_alarm_rate_mean"] == "nan"
                else f"{100 * float(r['false_alarm_rate_mean']):.1f} $\\pm$ {100 * float(r['false_alarm_rate_sd']):.1f}"
            )
            out.append(
                f"{where} & {ARM[r['arm']]} & {r['runs']} & "
                f"{100 * float(r['missed_rate_mean']):.1f} $\\pm$ {100 * float(r['missed_rate_sd']):.1f} & {alarm} \\\\"
            )
            previous = group
        return out

    for r in rows:
        tag = "official" if r["test_set"].startswith("official") else "matched"
        key = f"RV.err.{r['dataset']}.{tag}.{r['arm']}"
        put(f"{key}.missed", f"{100 * float(r['missed_rate_mean']):.1f}")
        if r["false_alarm_rate_mean"] != "nan":
            put(f"{key}.alarm", f"{100 * float(r['false_alarm_rate_mean']):.1f}")
        put(f"RV.err.{r['dataset']}.{tag}.present", f"{int(float(r['present_pairs'])):,}")
        put(f"RV.err.{r['dataset']}.{tag}.absent", f"{int(float(r['absent_pairs'])):,}")
    main_arms = {"U", "D", "BDS-Lite", "decoder", "kd_band", "decoder_aug", "kd_band_aug"}
    note = "% generated by analysis/revision/make_review_assets.py from posthoc_review_20261112/missed_false_alarm.csv"
    write(
        "tab_errors_main.tex",
        [
            note,
            r"\begin{tabular}{@{}llrrr@{}}",
            *head,
            *body(main_arms),
            r"\bottomrule",
            r"\end{tabular}",
        ],
    )
    write(
        "tab_s_review_errors.tex",
        [
            note,
            r"\begin{tabular}{llrrr}",
            *head,
            *body({r["arm"] for r in rows}),
            r"\bottomrule",
            r"\end{tabular}",
        ],
    )


def submitted() -> None:
    """A: submitted Table 2; B: the same checkpoints re-scored; C: retrained models (DSC, BF1)."""
    original = (GEN / "tab_s_original.tex").read_text()
    two = (GEN / "tab_two_sets.tex").read_text()
    for dataset, label in DATASET.items():
        m = re.search(rf"{label} & U-Net & ([0-9.]+) & [0-9.]+ & ([0-9.]+)", original)
        put(f"RV.sub.{dataset}.A.dsc", m.group(1))
        put(f"RV.sub.{dataset}.A.bf1", m.group(2))
        for tag, name in (("B", "original"), ("C", "retrained")):
            m = re.search(
                rf"{label}, {name} & U-Net & ([0-9.]+) \$\\pm\$ [0-9.]+ & [0-9.]+ \$\\pm\$ [0-9.]+ & ([0-9.]+)",
                two,
            )
            put(f"RV.sub.{dataset}.{tag}.dsc", m.group(1))
            put(f"RV.sub.{dataset}.{tag}.bf1", m.group(2))


def membership() -> None:
    """Membership of the 519 submitted ISIC2018 evaluation images, and empty-reference shares."""
    table = (GEN / "tab_s_membership.tex").read_text()
    for tag, label in (
        ("all", "All images, as originally reported"),
        ("train", "In these models' training set"),
        ("selection", "In their checkpoint-selection set"),
        ("heldout", "Held out from them"),
    ):
        put(f"RV.sub.isic2018.n.{tag}", re.search(rf"{re.escape(label)} & (\d+) &", table).group(1))
    for row in read("missed_false_alarm.csv"):
        tag = "official" if row["test_set"].startswith("official") else "matched"
        present, absent = int(float(row["present_pairs"])), int(float(row["absent_pairs"]))
        put(f"RV.err.{row['dataset']}.{tag}.pairs", f"{present + absent:,}")
        put(f"RV.err.{row['dataset']}.{tag}.absent.pct", f"{100 * absent / (present + absent):.0f}")


def published() -> None:
    """Main-text published-results table with the volume-level scores of this study's U-Net."""
    extra = (GEN / "numbers_extra.tex").read_text()

    def vol(dataset: str) -> str:
        m = re.search(rf"R@VOL\.{dataset}\.M0\.dsc\\endcsname\{{([0-9.]+)\}}", extra)
        value = f"{float(m.group(1)) / 100:.3f}"
        put(f"RV.vol.{dataset}.U", value)
        return value

    source = (GEN / "tab_published_text.tex").read_text().splitlines()
    ours = "no pretraining or augmentation"
    # ISIC2018: the per-image mean DSC of the matched-protocol U (main-text Table 4), not a
    # volume-level or pixel-pooled score (note b of the main-text table)
    matched = (GEN / "tab_lit_main.tex").read_text()
    isic_u = re.search(r"^ISIC2018 & U-Net & \$(0\.\d{4}) \\pm", matched, re.M).group(1)
    out = []
    for line in source:
        if line.startswith("ACDC & TransUNet") or line.startswith("Synapse & TransUNet"):
            out.append(r"\addlinespace")
        out.append(line)
        if line.startswith(" & CTO") and "0.9063" in line:
            out.append(rf" & U (this study, seeds 1--3)\tnote{{b}} & {isic_u} & -- & {ours} \\")
        if line.startswith(" & Swin-Unet") and "0.9000" in line:
            out.append(
                rf" & U (this study, seeds 1--3)\tnote{{c}} & {vol('acdc')} & -- & {ours} \\"
            )
        if line.startswith(" & CTO") and "0.8094" in line:
            out.append(
                rf" & U (this study, seeds 1--3)\tnote{{c}} & {vol('synapse')} & -- & {ours}, 14 cases \\"
            )
    if sum("this study" in line for line in out) != 3:
        raise ValueError("published table layout changed")
    out[0] = (
        "% generated by analysis/revision/make_review_assets.py from tab_published_text.tex and VOL keys"
    )
    write("tab_published_review.tex", out)


COLLAPSE_BINS = (r"<1\%", r"1-2\%", r"2-5\%", r">5\%")


def collapse_wide() -> None:
    """S8 table of missed structures and false alarms by reference area, one row per arm.

    Pivots the long table rl_tab_s_collapse.tex (one row per arm and area bin) without changing any
    displayed value: every cell of the long table appears once in the wide table, which the
    assertions check. Instances per seed depend only on dataset and bin, so they go in the header.
    """
    long = (GEN / "rl_tab_s_collapse.tex").read_text().splitlines()
    cells = [
        [c.strip() for c in line.rstrip("\\ ").split(" & ")]
        for line in long
        if line.count(" & ") == 6 and not line.startswith("Dataset")
    ]
    data: dict[str, dict[str, dict[str, list[str]]]] = {}
    count: dict[tuple[str, str], str] = {}
    for dataset, method, area, n, missed, alarm, dsc in cells:
        arm = data.setdefault(dataset, {}).setdefault(method, {})
        if area in arm:
            raise ValueError(f"duplicate row {dataset} {method} {area}")
        arm[area] = [missed, alarm, dsc]
        if area != "empty-reference":
            if count.setdefault((dataset, area), n) != n:
                raise ValueError(f"instances differ within {dataset} {area}")
            if alarm != "--":
                raise ValueError(f"false-alarm value in a non-empty bin: {dataset} {method} {area}")
        elif (n, missed, dsc) != ("--", "--", "--"):
            raise ValueError(f"unexpected values in empty-reference row: {dataset} {method}")
    used = 0
    lines = [
        "% generated by analysis/revision/make_review_assets.py::collapse_wide from"
        " rl_tab_s_collapse.tex (same values, one row per arm)",
        r"\begin{tabular}{@{}l" + "rr" * len(COLLAPSE_BINS) + "r@{}}",
        r"\toprule",
    ]
    for dataset, arms in data.items():
        bins = [b for b in COLLAPSE_BINS if (dataset, b) in count]
        pad = [""] * (2 * (len(COLLAPSE_BINS) - len(bins)))
        head1 = (
            ["Arm"]
            + [rf"\multicolumn{{2}}{{c}}{{{b} ($n={count[(dataset, b)]}$)}}" for b in bins]
            + pad
            + ["Empty ref."]
        )
        head2 = [""] + ["Missed", "DSC"] * len(bins) + pad + ["False al."]
        lines += [
            r"\multicolumn{"
            + str(2 + 2 * len(COLLAPSE_BINS))
            + r"}{@{}l}{\emph{"
            + dataset
            + r"}} \\",
            " & ".join(head1) + r" \\",
            " & ".join(head2) + r" \\",
            r"\midrule",
        ]
        for method, by_area in arms.items():
            row = [method]
            for b in bins:
                if b not in by_area:  # the long table has no row for this arm and bin
                    row += ["--", "--"]
                    continue
                missed, _, dsc = by_area.pop(b)
                row += [missed, dsc]
                used += 1
            row += pad
            row.append(by_area.pop("empty-reference")[1])
            used += 1
            if by_area:
                raise ValueError(f"unused bins for {dataset} {method}: {sorted(by_area)}")
            lines.append(" & ".join(row) + r" \\")
        lines.append(r"\midrule")
    if used != len(cells):
        raise ValueError(f"wide table uses {used} of {len(cells)} long-table rows")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    write("tab_s_collapse_wide.tex", lines)


def main() -> None:
    interaction()
    pooling()
    run_sd()
    errors()
    submitted()
    membership()
    published()
    collapse_wide()
    lines = ["% generated by analysis/revision/make_review_assets.py; do not edit"]
    lines += [rf"\expandafter\def\csname R@{k}\endcsname{{{v}}}" for k, v in sorted(KEYS.items())]
    write("numbers_review.tex", lines)
    (GEN / "keys_review.json").write_text(json.dumps(dict(sorted(KEYS.items())), indent=1) + "\n")
    print(f"{len(KEYS)} keys")
    for key in (
        "RV.int.all.boundary_f1.est",
        "RV.int.all.boundary_f1.text",
        "RV.int.all.boundary_f1.p",
        "RV.pool.dec.eq.text",
        "RV.pool.dec.noacdc.share",
        "RV.sd.acdc.min",
        "RV.sub.synapse.A.dsc",
        "RV.sub.synapse.B.dsc",
        "RV.vol.synapse.U",
    ):
        print(key, KEYS[key])


if __name__ == "__main__":
    main()
