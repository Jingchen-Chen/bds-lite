"""Keys and tables for the review round of 2026-11-12 (formatting only; no statistics here).

Reads results/posthoc_review_20261112/*.csv (written by posthoc_review_20261112.py), the
generated tables tab_s_original.tex and tab_two_sets.tex (submitted and re-scored values) and
writes paper/generated/{numbers_review.tex, keys_review.json,
tab_errors_main.tex, tab_s_review_errors.tex, tab_s_review_interaction.tex,
tab_s_review_pooling.tex, tab_s_review_run_sd.tex, tab_published_review.tex}.

    PYTHONPATH=src:. .venv/bin/python analysis/revision/make_review_assets.py
"""

