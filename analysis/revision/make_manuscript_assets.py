def gate_identity() -> None:
    """Gate -> identity at inference on the submitted BDS-Lite models (family G)."""
    largest = {}
    for r in rows(FAM / "family_statistics.csv"):
        if r["family"] != "G":
            continue
        value = float(r["mean_oriented_delta"])
        kind = "dist" if r["metric"] in ("hd95", "assd") else "overlap"
        largest[kind] = max(largest.get(kind, 0.0), abs(value))
        put(f"G.{r['dataset']}.{r['metric']}.practical", r["practical"])
    if largest:
        put("G.max.overlap", num(largest.get("overlap", 0.0), 4))
        put("G.max.dist", num(largest.get("dist", 0.0), 3))
    judgements = {VALUES[k] for k in VALUES if k.startswith("G.") and k.endswith(".practical")}
    if judgements:
        put("G.all.practical", "; ".join(sorted(judgements)))


