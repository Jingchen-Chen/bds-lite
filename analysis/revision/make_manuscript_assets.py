# ruff: noqa: E501  (LaTeX table literals)
"""Generate every number and table of the revised manuscript from result CSVs.

Output: paper/generated/{numbers.tex, tab_*.tex, missing.txt}.
numbers.tex defines keyed values used in the text as \\R{key}; a missing key renders a
red placeholder in the PDF (see main.tex), so pending results stay visible and no
number is typed by hand. Sources are listed in each generated table header.
"""

from __future__ import annotations

import csv
import json
import math
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "paper/generated"
FAM = ROOT / "results/tables/families"
METRICS = ["dsc", "iou", "boundary_f1", "hd95", "assd"]
MNAME = {"dsc": "DSC", "iou": "IoU", "boundary_f1": "BF1", "hd95": "HD95", "assd": "ASSD"}
DNAME = {"isic2018": "ISIC2018", "acdc": "ACDC", "synapse": "Synapse"}
UNIT = {"isic2018": "image", "acdc": "patient", "synapse": "case"}
VALUES: dict[str, str] = {}


def rows(path: Path) -> list[dict]:
    if not path.exists() or path.stat().st_size == 0:
        return []
    return list(csv.DictReader(path.open()))


def num(x, digits=4, sign=False) -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    text = f"{v:+.{digits}f}" if sign else f"{v:.{digits}f}"
    return text.replace("-", "$-$") if "-" in text else text


def pfmt(x) -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    return f"{v:.3f}" if v >= 0.001 else f"{v:.1e}".replace("e-0", "e-")


def put(key: str, value: str) -> None:
    VALUES[key] = value


def digits(metric: str) -> int:
    return 2 if metric in ("hd95", "assd") else 3


def families() -> list[dict]:
    data = rows(FAM / "family_statistics.csv")
    for r in data:
        key = f"{r['family']}.{r['dataset']}.{r['method']}.{r['reference']}.{r['metric']}"
        d = 2 if r["metric"] in ("hd95", "assd") else 4
        put(key + ".delta", num(r["mean_oriented_delta"], d, sign=True))
        put(key + ".ci", f"[{num(r['ci95_low'], d, True)}, {num(r['ci95_high'], d, True)}]")
        put(key + ".holm", pfmt(r["p_holm"]))
        put(key + ".p", pfmt(r["p_raw"]))
        put(key + ".practical", r["practical"])
        put(key + ".n", r["n_clusters"])
    return data


def summaries() -> dict:
    table = {}
    for r in rows(FAM / "method_summary.csv"):
        if r["complete"] != "True":
            continue
        table[(r["dataset"], r["method"])] = r
        for m in METRICS:
            d = digits(m)
            put(f"mean.{r['dataset']}.{r['method']}.{m}", num(r[f"{m}_mean"], d))
            put(f"sd.{r['dataset']}.{r['method']}.{m}", num(r[f"{m}_sd"], d))
    return table


def write(name: str, lines: list[str]) -> None:
    (OUT / name).write_text("\n".join(lines) + "\n")


def mean_table(summary, methods, name, caption_source) -> None:
    lines = [f"% generated by analysis/revision/make_manuscript_assets.py from {caption_source}"]
    lines += [r"\begin{tabular}{llccccc}", r"\toprule"]
    lines.append(
        r"Dataset & Method & DSC $\uparrow$ & IoU $\uparrow$ & BF1 $\uparrow$ & HD95 (px) $\downarrow$ & ASSD (px) $\downarrow$ \\"
    )
    labels = {}
    for r in rows(FAM / "method_summary.csv"):
        labels[r["method"]] = r["label"]
    for dataset in DNAME:
        lines.append(r"\midrule")
        first = True
        for method in methods:
            r = summary.get((dataset, method))
            label = labels.get(method, method)
            cells = (
                [
                    f"${num(r[f'{m}_mean'], digits(m))} \\pm {num(r[f'{m}_sd'], digits(m))}$"
                    for m in METRICS
                ]
                if r
                else [r"\textit{pending}"] * 5
            )
            lines.append(
                f"{DNAME[dataset] + (' (test)' if dataset != 'isic2018' else ' (official test)') if first else ''} & {label} & "
                + " & ".join(cells)
                + r" \\"
            )
            first = False
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(name, lines)


def stats_table(data, family, methods, reference, name) -> None:
    lines = [f"% generated from results/tables/families/family_statistics.csv (family {family})"]
    lines += [r"\begin{tabular}{lllrlll}", r"\toprule"]
    lines.append(
        r"Dataset ($n$ units) & Contrast & Metric & Oriented $\Delta$ & 95\% CI & Holm $p$ & SESOI judgement \\"
    )
    labels = {r["method"]: r["label"] for r in rows(FAM / "method_summary.csv")}
    for dataset in DNAME:
        lines.append(r"\midrule")
        for method in methods:
            sub = [
                r
                for r in data
                if r["family"] == family
                and r["dataset"] == dataset
                and r["method"] == method
                and r["reference"] == reference
            ]
            if not sub:
                lines.append(
                    f"{DNAME[dataset]} & {labels.get(method, method)} vs {labels.get(reference, reference)} & \\multicolumn{{5}}{{l}}{{\\textit{{pending}}}} \\\\"
                )
                continue
            for r in sub:
                d = 2 if r["metric"] in ("hd95", "assd") else 4
                mark = "$^{*}$" if r["decision"] != "no decision" else ""
                lines.append(
                    f"{DNAME[dataset]} ({UNIT[dataset]}, {r['n_clusters']}) & {labels.get(method, method)} vs {labels.get(reference, reference)} & {MNAME[r['metric']]} & "
                    f"{num(r['mean_oriented_delta'], d, True)}{mark} & [{num(r['ci95_low'], d, True)}, {num(r['ci95_high'], d, True)}] & "
                    f"{pfmt(r['p_holm'])} & {r['practical']} \\\\"
                )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(name, lines)


def compact_delta_table(data, family, methods, reference, name) -> None:
    """Methods x (dataset, metric) oriented deltas; * = Holm p<0.05 with CI excluding 0."""
    labels = {r["method"]: r["label"] for r in rows(FAM / "method_summary.csv")}
    lines = [f"% generated from family_statistics.csv (family {family}, reference {reference})"]
    lines += [r"\begin{tabular}{l" + "r" * 15 + "}", r"\toprule"]
    lines.append(
        " & " + " & ".join(f"\\multicolumn{{5}}{{c}}{{{DNAME[d]}}}" for d in DNAME) + r" \\"
    )
    lines.append("Arm & " + " & ".join(MNAME[m] for _ in DNAME for m in METRICS) + r" \\")
    lines.append(r"\midrule")
    for method in methods:
        lines.append(delta_row(data, family, method, reference, labels.get(method, method)))
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(name, lines)


def delta_row(data, family, method, reference, label) -> str:
    cells = []
    for dataset in DNAME:
        for metric in METRICS:
            hit = [
                r
                for r in data
                if r["family"] == family
                and r["dataset"] == dataset
                and r["method"] == method
                and r["reference"] == reference
                and r["metric"] == metric
            ]
            if not hit:
                cells.append("--")
                continue
            r = hit[0]
            d = 2 if metric in ("hd95", "assd") else 3
            star = "$^{*}$" if r["decision"] != "no decision" else ""
            cells.append(num(r["mean_oriented_delta"], d, True) + star)
    return f"{label} & " + " & ".join(cells) + r" \\"


def comparator_table(data) -> None:
    """Two panels: arms vs pipeline-matched U-Net (M0; BDS-Lite M6 from family P-matched for scale)
    and comparators vs pipeline-matched BDS-Lite (M6; family C-vs-M6)."""
    labels = {r["method"]: r["label"] for r in rows(FAM / "method_summary.csv")}
    lines = ["% generated from family_statistics.csv (families P-matched, C, C-vs-M6)"]
    lines += [r"\begin{tabular}{l" + "r" * 15 + "}", r"\toprule"]
    lines.append(
        " & " + " & ".join(f"\\multicolumn{{5}}{{c}}{{{DNAME[d]}}}" for d in DNAME) + r" \\"
    )
    lines.append("Arm & " + " & ".join(MNAME[m] for _ in DNAME for m in METRICS) + r" \\")
    lines.append(r"\midrule")
    lines.append(r"\multicolumn{16}{l}{\emph{versus U-Net (M0)}} \\")
    lines.append(delta_row(data, "P-matched", "M6", "M0", "BDS-Lite (M6)"))
    for method in ["GSL", "C1", "C3", "C4"]:
        lines.append(delta_row(data, "C", method, "M0", labels.get(method, method)))
    lines.append(r"\midrule")
    lines.append(r"\multicolumn{16}{l}{\emph{versus BDS-Lite (M6)}} \\")
    for method in ["GSL", "C1", "C3", "C4"]:
        lines.append(delta_row(data, "C-vs-M6", method, "M6", labels.get(method, method)))
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("tab_comparators.tex", lines)


