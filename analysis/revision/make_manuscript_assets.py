def auxiliary_share() -> None:
    """F5: weighted auxiliary losses relative to CE+Dice in epoch 1 of WP5 seed-1 runs."""
    for dataset in DNAME:
        path = ROOT / f"results/revision_runs/{dataset}_wp5_full_seed1/history.json"
        if not path.exists():
            continue
        first = json.loads(path.read_text())[0]["train"]
        seg = first["ce"] + first["dice"]
        aux = 0.05 * (first["boundary_bce"] + first["boundary_dice"]) + 0.05 * first["distill"]
        put(f"AUX.{dataset}.share", num(100 * aux / seg, 1))
        put(f"AUX.{dataset}.sdf", num(first["surface"], 3, True))


def generic_table(
    source: Path, name: str, columns: list[tuple[str, str, int | None]], note: str
) -> None:
    """columns: (csv field, header, digits or None for text)."""
    data = rows(source)
    labels = {r["method"]: r["label"] for r in rows(FAM / "method_summary.csv")}
    lines = [f"% generated from {source.relative_to(ROOT)}; {note}"]
    lines += [r"\begin{tabular}{" + "l" * len(columns) + "}", r"\toprule"]
    lines.append(" & ".join(h for _, h, _ in columns) + r" \\")
    lines.append(r"\midrule")
    for r in data:
        cells = []
        for field, _, d in columns:
            value = r.get(field, "")
            if field == "method":
                value = labels.get(value, value)
            elif field == "dataset":
                value = DNAME.get(value, value)
            elif d is not None:
                value = num(value, d)
            cells.append(str(value).replace("%", r"\%").replace("_", r"\_"))
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(name, lines)


